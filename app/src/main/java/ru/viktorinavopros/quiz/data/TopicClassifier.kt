    fun classify(text: String, siteTopic: Topic? = null): Topic {
        val scores = HashMap<Topic, Int>()
        for (rule in rules) {
            var score = 0
            for (match in rule.regex.findAll(text)) {
                score += when {
                    match.value.length >= 8 -> 3
                    match.value.length >= 5 -> 2
                    else -> 1
                }
            }
            if (score > 0) scores[rule.topic] = (scores[rule.topic] ?: 0) + score
        }

        val best = scores.maxByOrNull { it.value }
        val bestScore = best?.value ?: 0

        // Если вопрос лежит в тематическом разделе сайта, доверяем ему,
        // пока текстовые признаки не указывают на другую тему очень уверенно.
        if (siteTopic != null && siteTopic != Topic.MIXED) {
            val siteScore = scores[siteTopic] ?: 0
            val otherBest = scores.filterKeys { it != siteTopic }.maxByOrNull { it.value }?.value ?: 0
            if (siteScore >= otherBest || otherBest < 6) return siteTopic
            return scores.maxByOrNull { it.value }!!.key
        }

        return if (bestScore >= 2) best!!.key else Topic.MIXED
    }
